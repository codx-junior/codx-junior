"""Where a finding lives: path, comment, docstring or rule table.

The CISO detectors read raw text. Without a notion of *context* they cannot
tell a rule from a sentence about that rule:

* a lock file is 3 000 hashes and URLs, not 3 000 credentials;
* ``TOKEN_ARG_PREFIX = "http.extraheader="`` is a config key, not a token;
* ``system: Optional[str]`` is a type annotation, not a chat role;
* ``re.compile(r"...meterpreter...")`` is the detector, not the attack;
* ``Do not disable security settings`` is a safety instruction, not a bypass.

This module is the one place that answers those questions. It is deliberately
stdlib-only and deterministic: the same classification runs inside the API, the
git hook and a slim container. Detectors keep their rule tables; they ask here
whether a match is executable, documentation, data or an identifier before
they raise a blocking severity.

Nothing here *silences* a rule. A non-executable match is still reported, but
at a lower severity, so a real credential written into a docstring is visible
without turning every documentation example into a blocked commit.

Made with ❤️ by codx-junior
"""

import os
import re
from typing import List, Optional, Tuple

#: Path segments holding runtime data generated by the platform itself: task
#: transcripts, chat turns, autonomy state. Nothing there is executed, and the
#: files quote code, diffs, logs and commands verbatim, so a code-shaped rule
#: matches a *quotation*.
DATA_PATH_SEGMENTS = frozenset({".codx"})

#: Extensions whose content is long-form prose (documentation). A Markdown file
#: is read by a human, never executed, so a command quoted in a troubleshooting
#: table must not block a change -- it is reported as ``low`` instead.
PROSE_EXTENSIONS = frozenset({
    ".md", ".markdown", ".mdx", ".rst", ".txt", ".adoc", ".log",
})

#: Generated dependency files. Their content is hashes, URLs and package names:
#: the entropy detector produced ~3 500 findings on a single ``uv.lock`` and
#: buried every real one. Known credential shapes and URL credentials are still
#: checked in these files; only the unknown-token entropy heuristic is skipped.
LOCK_FILE_NAMES = frozenset({
    "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml",
    "bun.lock", "bun.lockb", "deno.lock", "poetry.lock", "pipfile.lock",
    "uv.lock", "pdm.lock", "requirements.lock", "cargo.lock", "go.sum",
    "composer.lock", "gemfile.lock", "gradle.lockfile", "mix.lock",
    "podfile.lock", "packages.lock.json", "flake.lock",
})

#: Folders that must CONTAIN the patterns the detectors look for: the detector
#: tables, their documentation and the security fixtures. They are reported as
#: ``low`` (never blocking) for code/injection rules; ``secret.*`` still runs at
#: full strength, so a real credential written there is still found.
DETECTOR_CORPUS_MARKERS = (
    "/security/ciso/",
    "/tests/security/",
)

#: Generated reports, caches, duplicated trees and runtime home folders. They
#: are not product source, and a project scan that walks them reports certs,
#: fixture tokens and minified assets as findings. Precise rules still inspect
#: these paths on a diff/write gate; only the unbounded project walk skips them.
GENERATED_PATH_FRAGMENTS = (
    "/pytest-of-",
    "/.vitepress/cache/",
    "/.vitepress/dist/",
    "/.launchpadlib/",
    "/cachedprofilesdata/",
    "/.vscode-server/",
    "/.vscodium-server/",
    "/site-packages/",
    "/.tox/",
    "/.ruff_cache/",
    "/htmlcov/",
    "/coverage/",
    "/client/public/wiki/",
    "/client/client/",
    "/client/lighthouse_report.json",
    "/config/ssl/",
    "/config/.vnc/",
    "/.local/share/",
    "/github_issues.html",
    "/tmp/",
    "/wiki/docs.json",
    "/wiki/.vitepress/",
)

#: Extensions whose content is machine-generated binary/text material. The
#: entropy heuristic is meaningless there (certificate bodies, minified CSS,
#: source maps); precise token/private-key rules still run.
ASSET_EXTENSIONS = frozenset({
    ".pem", ".crt", ".cer", ".key", ".pub", ".p12", ".pfx", ".jks", ".keystore",
    ".css", ".map", ".svg", ".min.js",
})


def normalise_path(path: Optional[str]) -> str:
    """Return *path* in a comparison-friendly shape (posix, lower case)."""
    return (path or "").replace("\\", "/").lower()


def is_data_path(path: Optional[str]) -> bool:
    """Return True when *path* is agent/runtime data instead of source code.

    Args:
        path: File path.

    Returns:
        bool: True for a path under a ``.codx`` control-plane folder.
    """
    if not path:
        return False
    normalised = normalise_path(path)
    if normalised.startswith("knowledge://"):
        # A knowledge chunk is being ingested into a prompt, not committed as
        # repository data: a stored instruction there is live.
        return False
    return any(part in DATA_PATH_SEGMENTS for part in normalised.split("/"))


def is_prose_path(path: Optional[str]) -> bool:
    """Return True when *path* is documentation, i.e. never executed.

    Args:
        path: File path.

    Returns:
        bool: True for Markdown and other long-form text files.
    """
    if not path:
        return False
    return os.path.splitext(normalise_path(path))[1] in PROSE_EXTENSIONS


def is_lock_file(path: Optional[str]) -> bool:
    """Return True when *path* is a generated dependency lock file.

    Args:
        path: File path.

    Returns:
        bool: True for ``uv.lock``, ``package-lock.json``, ``Cargo.lock``, ...
    """
    if not path:
        return False
    name = os.path.basename(normalise_path(path))
    return name in LOCK_FILE_NAMES or name.endswith(".lock")


def is_detector_corpus_path(path: Optional[str]) -> bool:
    """Return True when *path* is the CISO detector corpus or its fixtures.

    Args:
        path: File path.

    Returns:
        bool: True for ``.../security/ciso/...`` and ``.../tests/security/...``.
    """
    posix = "/" + normalise_path(path).lstrip("/")
    return any(marker in posix for marker in DETECTOR_CORPUS_MARKERS)


def is_generated_path(path: Optional[str]) -> bool:
    """Return True for a generated report/cache/runtime-home path.

    Args:
        path: File or directory path.

    Returns:
        bool: True for ``pytest-of-*``, ``client/public/wiki``, cert caches, ...
    """
    posix = "/" + normalise_path(path).lstrip("/")
    if not posix.endswith("/"):
        posix += "/"
    if "/workspaces/" in posix and (
        "/config/" in posix or "/kasm-user/" in posix
    ):
        # Runtime home folders of the installer workspace images: caches,
        # certificates and browser profiles, not product source.
        return True
    return any(fragment in posix for fragment in GENERATED_PATH_FRAGMENTS)


def is_knowledge_path(path: Optional[str]) -> bool:
    """Return True for content being ingested into the knowledge base.

    Args:
        path: Synthetic scan path (``knowledge://<source>``).

    Returns:
        bool: True for the knowledge-ingestion namespace.
    """
    return normalise_path(path).startswith("knowledge://")


def is_test_path(path: Optional[str]) -> bool:
    """Return True when *path* is a test file or lives in a test folder.

    Args:
        path: File path.

    Returns:
        bool: True for ``tests/``, ``test_*.py``, ``*.spec.js``, ...
    """
    if not path:
        return False
    posix = "/" + normalise_path(path).lstrip("/")
    if posix.startswith("/knowledge://"):
        # Ingested content is evaluated as content, not as a repository test.
        return False
    name = os.path.basename(posix)
    if "/tests/" in posix or "/test/" in posix:
        return True
    return (
        name.startswith("test_")
        or name.endswith("_test.py")
        or ".test." in name
        or ".spec." in name
    )


def is_asset_path(path: Optional[str]) -> bool:
    """Return True for certificate/key material and minified assets.

    Args:
        path: File path.

    Returns:
        bool: True for ``.pem``, ``.crt``, ``.css``, source maps, ...
    """
    if not path:
        return False
    return normalise_path(path).endswith(tuple(ASSET_EXTENSIONS))


def is_source_code_path(path: Optional[str]) -> bool:
    """Return True when *path* has a source/script/configuration extension.

    Args:
        path: File path.

    Returns:
        bool: True for ``.py``, ``.js``, ``.ts``, ``.sh``, ``.yml``, ...
    """
    if not path:
        return False
    return normalise_path(path).endswith((
        ".py", ".pyi", ".js", ".mjs", ".cjs", ".jsx", ".ts", ".tsx", ".vue",
        ".rb", ".php", ".pl", ".go", ".rs", ".java", ".kt", ".cs", ".sh",
        ".bash", ".zsh", ".fish", ".ps1", ".bat", ".cmd", ".yml", ".yaml",
        ".toml", ".tf", ".hcl", ".sql", ".dockerfile",
    ))


# -----------------------------------------------------------------------------
# Position helpers
# -----------------------------------------------------------------------------
def line_start(text: str, index: int) -> int:
    """Return the offset of the first character of the line containing *index*."""
    return max(0, text.rfind("\n", 0, max(0, index)) + 1)


def line_end(text: str, index: int) -> int:
    """Return the offset just past the line containing *index*."""
    end = text.find("\n", max(0, index))
    return len(text) if end == -1 else end


def line_prefix(text: str, index: int) -> str:
    """Return the part of the line before *index*."""
    return text[line_start(text, index):max(0, index)]


def line_text(text: str, index: int) -> str:
    """Return the whole line containing *index*."""
    return text[line_start(text, index):line_end(text, index)]


def _find_unquoted(text: str, marker: str) -> int:
    """Return the offset of *marker* outside a simple quoted string, or ``-1``."""
    quote = ""
    escaped = False
    index = 0
    while index < len(text):
        char = text[index]
        if escaped:
            escaped = False
        elif char == "\\":
            escaped = True
        elif quote:
            if char == quote:
                quote = ""
        elif char in ("'", '"', "`"):
            quote = char
        elif text.startswith(marker, index):
            return index
        index += 1
    return -1


def is_comment_position(text: str, index: int) -> bool:
    """Return True when *index* sits in a line comment.

    Handles the comment markers of Python/Shell/YAML (``#``), JavaScript,
    TypeScript, Go and Rust (``//``, ``/*``) and block-comment continuation
    lines (`` * ``). The check is deliberately conservative: a ``#`` inside a
    quoted string does not make the line a comment.

    Args:
        text: Payload.
        index: Match offset.

    Returns:
        bool: True when the match is documentation, not executable code.
    """
    prefix = line_prefix(text, index)
    stripped = prefix.lstrip()
    if stripped.startswith(("#", "//", "/*")):
        return True
    if stripped.startswith("* "):
        return True
    for marker in ("#", "//"):
        if _find_unquoted(prefix, marker) != -1:
            return True
    return False


_TRIPLE_QUOTED = re.compile(r'(?s)("""|\'\'\')(.*?)\1')


def triple_quoted_spans(text: str) -> List[Tuple[int, int]]:
    """Return the spans of triple-quoted strings in *text*.

    Any triple-quoted string is treated as documentation: a docstring, a
    doctest, a SQL block. It is still reported, but never at blocking severity.

    Args:
        text: Payload.

    Returns:
        list: ``(start, end)`` offsets.
    """
    if '"""' not in (text or "") and "'''" not in (text or ""):
        return []
    return [match.span() for match in _TRIPLE_QUOTED.finditer(text or "")]


def is_docstring_position(text: str, index: int) -> bool:
    """Return True when *index* is inside a triple-quoted string."""
    return any(start <= index < end for start, end in triple_quoted_spans(text))


def is_rule_definition_line(text: str, index: int) -> bool:
    """Return True when the match is part of a detector/rule definition.

    A rule table is a data structure full of the exact strings the detector
    looks for. Treating it as executable code makes the security package flag
    itself, and the noise is indistinguishable from the real findings.

    Args:
        text: Payload.
        index: Match offset.

    Returns:
        bool: True for a ``re.compile(...)``, ``RuleDescriptor(...)`` or
        doctest line.
    """
    current = line_text(text, index)
    previous_start = line_start(text, max(0, index))
    previous_end = max(0, previous_start - 1)
    previous = text[line_start(text, previous_end):previous_end] if previous_end else ""
    current_end = line_end(text, index)
    markers = ("re.compile(", "re.match(", "re.search(", "RuleDescriptor(")
    if any(marker in current for marker in markers):
        return True
    # A rule tuple is often wrapped across lines, with ``re.compile`` one or
    # two lines away from the title that carries the matched word. A short
    # window is enough and leaves a real executable line high.
    before = text[max(0, index - 400): max(0, index)]
    after = text[current_end: min(len(text), current_end + 400)]
    if any(marker in before or marker in after for marker in markers):
        return True
    if ">>>" in line_prefix(text, index):
        return True
    return False


def is_documentation_position(
    text: str,
    index: int,
    path: Optional[str] = None,
) -> bool:
    """Return True when a match is documentation rather than executable code.

    Args:
        text: Payload.
        index: Match offset.
        path: File the payload belongs to.

    Returns:
        bool: True for prose files, comments, docstrings, doctests and rule
        tables. A secret found here is still reported, only as ``low``.
    """
    if is_prose_path(path):
        return True
    if is_comment_position(text, index):
        return True
    if is_docstring_position(text, index):
        return True
    return is_rule_definition_line(text, index)


#: Wording that marks a match as a description of an attack rather than the
#: attack itself: a rule catalogue, a security guide, a test fixture.
_DESCRIPTION_CONTEXT_PATTERN = re.compile(
    r"(?i)(?:\bexample\b(?!\.)|\be\.g\.|\bfor instance\b|\bsample\b|\bfixture\b|"
    r"\bplaceholder\b|\bdummy\b|\bredacted\b|\bdocumentation\b|\bpattern\b|"
    r"\brule\b|\bdetects?\b|\btries? to\b|\battempts? to\b|\bquoted\b|"
    r"\bquotation\b|\bsuch as\b|\bfor example\b(?!\.))"
)
_DESCRIPTION_WINDOW = 240


def is_description_context(text: str, index: int) -> bool:
    """Return True when the surrounding text *describes* an instruction.

    Args:
        text: Payload.
        index: Match offset.

    Returns:
        bool: True when a documentation marker is nearby.
    """
    window = text[max(0, index - _DESCRIPTION_WINDOW): index + _DESCRIPTION_WINDOW]
    return bool(_DESCRIPTION_CONTEXT_PATTERN.search(window))


#: A negation before an imperative ("Do not disable security") makes the
#: sentence a safety rule, not a bypass instruction.
_NEGATION_PATTERN = re.compile(
    r"(?i)\b(?:do\s+not|don't|does\s+not|never|must\s+not|should\s+not|"
    r"shall\s+not|avoid|cannot|can't|no\s+need\s+to)\b"
    r"[^.!?\n]{0,48}$"
)


def is_negated(text: str, index: int) -> bool:
    """Return True when an imperative at *index* is negated just before it.

    Args:
        text: Payload.
        index: Start offset of the imperative.

    Returns:
        bool: True for ``Do not disable ...`` / ``never bypass ...``.
    """
    prefix = text[max(0, index - 80): max(0, index)]
    return bool(_NEGATION_PATTERN.search(prefix))


def is_url_value_without_userinfo(text: str, index: int) -> bool:
    """Return True when *index* belongs to an HTTP URL with no credentials.

    URLs carry long random-looking path segments (a Google thumbnail id, a
    package hash) that are not credentials. A URL that embeds ``user:pass@`` is
    excluded, so the generic entropy rule still sees the password itself.

    Args:
        text: Payload.
        index: Match offset.

    Returns:
        bool: True for a URL fragment outside the userinfo part.
    """
    start = max(0, index)
    while start > 0 and not text[start - 1].isspace():
        start -= 1
    end = min(len(text), index)
    while end < len(text) and not text[end].isspace():
        end += 1
    token = text[start:end]
    scheme = token.find("://")
    if scheme == -1 or scheme >= index - start:
        return False
    return "@" not in token[: index - start]


def is_label_value(value: str) -> bool:
    """Return True when *value* is a plain label/identifier, not a credential.

    Args:
        value: Assigned value.

    Returns:
        bool: True for ``settings``, ``file``, ``x-access-token``, ...
    """
    candidate = (value or "").strip()
    if not candidate or len(candidate) > 80:
        return False
    return bool(re.fullmatch(r"[A-Za-z][A-Za-z0-9_.:@/-]{0,79}", candidate))


def is_metadata_key(key: str) -> bool:
    """Return True when *key* names configuration metadata, not a secret.

    ``TOKEN_ARG_PREFIX``, ``DEFAULT_TOKEN_USERNAME``, ``GIT_ACCESS_TOKEN_MASK``
    and ``secret_source`` contain a credential word but store a label, a header
    name or a source enum. The assignment rule fired on every one of them.

    Args:
        key: Left-hand side identifier.

    Returns:
        bool: True for a metadata key.
    """
    return bool(re.search(
        r"(?i)(?:^|_)(?:source|name|file|path|folder|prefix|suffix|type|kind|"
        r"mode|mask|username|user|url|env|var|variable|count|limit|size|field|"
        r"header|scheme|format|provider|service|host|algorithm)$",
        (key or "").strip(),
    ))


_TOKEN_VERB_KEYS = frozenset({"tokenize", "tokenizer", "tokenization"})


def is_token_metadata_key(key: str) -> bool:
    """Return True for keys whose name merely contains ``token``.

    Args:
        key: Left-hand side identifier.

    Returns:
        bool: True for ``tokenize``, ``tokenizer``, ...
    """
    return (key or "").strip().lower() in _TOKEN_VERB_KEYS
